import type { ArchiveJob, PipelineStep, PipelineStepKey, PipelineStepStatus } from "@/lib/domain/types";
import { daysAgo, hoursAgo, minutesAgo } from "./clock";

type StepSpec = Partial<Omit<PipelineStep, "key">> & { status: PipelineStepStatus };

function steps(spec: Record<PipelineStepKey, StepSpec>): PipelineStep[] {
  return (Object.keys(spec) as PipelineStepKey[]).map((key) => ({
    key,
    status: spec[key].status,
    at: spec[key].at ?? null,
    recordCount: spec[key].recordCount ?? null,
    detail: spec[key].detail ?? null,
    error: spec[key].error ?? null,
  }));
}

const P = (at: string, recordCount: number | null, detail?: string): StepSpec => ({ status: "passed", at, recordCount, detail });
const PENDING: StepSpec = { status: "pending" };

function batches(total: number, size: number): number {
  return Math.ceil(total / size);
}

